// ── 用 Claude API 生成（如果有 key）──
async function generateWithClaude(topic, dateInfo) {
  const apiKey = process.env.ANTHROPIC_API_KEY;
  if (!apiKey) return null;

  try {
    const { default: Anthropic } = await import('@anthropic-ai/sdk');
    const client = new Anthropic({ apiKey });

    const topicNames = {
      trust: '保險金信託（保單與信託結合、身後規劃、資產保全）',
      retire: '退休規劃（退休缺口試算、長照準備、老後現金流）',
      insurance: '保險規劃（壽險、醫療險、長照險、保單健診）',
      estate: '不動產活化（以房養老、不動產信託、不動產活化）',
    };

    const prompt = `你是 Weber，一位擁有超過十年經驗的保險理財顧問，服務過三百多位客戶。
今天是 ${dateInfo.dateLabel}。
請以「${topicNames[topic]}」為主題，生成今日社群文案。

格式要求：
請用 JSON 格式回覆，包含以下欄位：
- keywords: 陣列，3~5個關鍵字詞（字串陣列）
- summary: 200~350字的今日觀點，給客戶看的市場/規劃洞察，語氣專業但親切，繁體中文
- fb: Facebook 貼文，280~400字，有故事感、真實感，結尾邀請私訊，繁體中文
- ig: Instagram 貼文，120~180字，簡潔有力，加 5~7 個 hashtag，繁體中文
- line: LINE 貼文，60~80字，親切直接，加一個 emoji，繁體中文

重要風格要求：
- 用真實案例或數據開場，增加可信度
- 語氣像朋友在聊天，不要太正式
- 不要推銷，要提供真正有用的資訊
- 結尾都要有「私訊我」的 CTA
- 不要用「【】」標題格式在 fb/ig/line 貼文裡

只回覆 JSON，不要其他文字。`;

    const msg = await client.messages.create({
      model: 'claude-haiku-4-5-20251001',
      max_tokens: 1500,
      messages: [{ role: 'user', content: prompt }],
    });

    const text = msg.content[0].text.trim();
    const jsonMatch = text.match(/\{[\s\S]+\}/);
    if (!jsonMatch) return null;
    return JSON.parse(jsonMatch[0]);
  } catch (e) {
    console.warn('Claude API failed:', e.message);
    return null;
  }
}

// ── 主程式 ──
async function main() {
  const dateInfo = getTaiwanDate();
  const topic = TOPICS[dateInfo.dayOfWeek];

  console.log(`📅 ${dateInfo.dateLabel}`);
  console.log(`📌 今日主題：${topic}`);

  let content;

  // 嘗試用 Claude API
  if (process.env.ANTHROPIC_API_KEY) {
    console.log('🤖 使用 Claude API 生成...');
    content = await generateWithClaude(topic, dateInfo);
    if (content) console.log('✅ Claude API 生成成功');
    else console.log('⚠️ Claude API 失敗，改用模板');
  }

  // fallback 到模板
  if (!content) {
    console.log('📝 使用內建模板...');
    content = TEMPLATES[topic];
  }

  const brief = {
    date: dateInfo.date,
    dateLabel: dateInfo.dateLabel,
    topic,
    keywords: content.keywords,
    summary: content.summary,
    fb: content.fb,
    ig: content.ig,
    line: content.line,
  };

  writeFileSync(OUTPUT, JSON.stringify(brief, null, 2), 'utf-8');
  console.log(`✅ data/brief.json 已更新`);
  console.log(`📄 摘要預覽：${brief.summary.slice(0, 60)}...`);
}

main().catch(e => { console.error(e); process.exit(1); });
