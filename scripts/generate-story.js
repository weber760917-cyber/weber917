async function main() {
  const dateInfo = getTaiwanDate();
  const topic = getTodayTopic(dateInfo.dayOfWeek);
  console.log(`📅 ${dateInfo.dateLabel}  📌 主題：${topic}`);

  // 讀取現有 stories.json
  let stories = [];
  try {
    stories = JSON.parse(readFileSync(STORIES_FILE, 'utf-8'));
  } catch { console.log('stories.json 不存在，從空陣列開始'); }

  // 生成新故事
  let tpl = null;
  if (process.env.ANTHROPIC_API_KEY) {
    console.log('🤖 Claude API 生成中...');
    tpl = await generateWithClaude(topic, dateInfo);
    if (tpl) console.log('✅ Claude API 成功');
    else console.log('⚠️ 改用模板');
  }
  if (!tpl) tpl = getStoryTemplate(topic);

  // 建立新故事物件
  const newStory = {
    id: `auto_${dateInfo.date}`,
    date: dateInfo.date.slice(0,7).replace(/-/g, '.'),
    tags: [topic === 'estate' ? 'realestate' : topic],
    tagLabels: [{ trust: '信託保全', retire: '退休警示', insurance: '保險陷阱', estate: '不動產' }[topic]],
    title: tpl.title,
    meta: tpl.meta || `${dateInfo.dateLabel} 自動生成`,
    quote: tpl.quote,
    solution: tpl.solution,
    fb: tpl.fb,
    ig: tpl.ig,
    line: tpl.line,
  };

  // 加到最後（網站會 reverse 顯示，所以最後的最先顯示）
  stories.push(newStory);

  // 最多保留 MAX_STORIES 篇
  if (stories.length > MAX_STORIES) {
    stories = stories.slice(stories.length - MAX_STORIES);
  }

  writeFileSync(STORIES_FILE, JSON.stringify(stories, null, 2), 'utf-8');
  console.log(`✅ stories.json 已更新（共 ${stories.length} 篇，今日新增：${tpl.title}）`);
}

main().catch(e => { console.error(e); process.exit(1); });
